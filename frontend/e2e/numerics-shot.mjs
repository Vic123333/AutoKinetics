import { chromium } from "@playwright/test";
const [base, out, example] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(base);
await page.getByRole("heading", { name: "Beispielbibliothek" }).waitFor();
await page.getByRole("button", { name: new RegExp(example) }).click();
await page.getByRole("tab", { name: "Numerik" }).click();
await page.getByRole("button", { name: "Analyse starten" }).click();
await page.getByRole("heading", { name: "Empfehlung" }).waitFor({ timeout: 120000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/numerics.png`, fullPage: true });
await page.getByRole("button", { name: "Übernehmen & simulieren" }).click();
await page.getByText("Konzentrationsverlauf").waitFor({ timeout: 60000 });
await page.waitForTimeout(1000);
await page.screenshot({ path: `${out}/after-apply.png` });
console.log("errors:", errors);
await browser.close();
